import assert from 'node:assert/strict';

const root = 'http://localhost:3000/api/halls';
const post = (url, body) => fetch(url, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
const created = await (await post(root, { title: 'San Diego day trip', scenario: 'san-diego' })).json();
const named = await (await post(root, { title: 'Weekend with friends' })).json();
assert.equal((await (await fetch(`${root}/${named.token}`)).json()).title, 'Weekend with friends');
assert.equal((await post(root, { title: '   ' })).status, 400);
const url = `${root}/${created.token}`;
assert.equal((await fetch(`${root}/invalid-token`)).status, 404);
assert.equal((await fetch(url, { method: 'POST', body: '{bad' })).status, 400);
assert.equal((await post(url, { type: 'message', displayName: 'A', text: 'x'.repeat(9000) })).status, 413);
const initial = await (await fetch(url)).json();
assert.equal(initial.travelers.length, 4);
assert.equal(initial.phase, 'Preparing');
assert.equal(initial.mode, 'sqlite');
assert.equal(initial.title, 'San Diego day trip');
const first = post(url, { type: 'replay' });
await new Promise(resolve => setTimeout(resolve, 500));
const duplicate = await post(url, { type: 'replay' });
assert.equal(duplicate.status, 409);
assert.equal((await first).status, 200);
let state = await (await fetch(url)).json();
assert.equal(state.phase, 'Agreed');
assert.equal(state.plans[0].costPerPerson, 128);
assert.equal(typeof state.events[0].createdAt, 'string');
assert.equal(Object.values(state.plans[0].votes).filter(Boolean).length, 4);
await post(url, { type: 'message', displayName: 'Aarsh', text: 'I can leave after breakfast.' });
await post(url, { type: 'reduceBudget', amount: 90 });
const revised = post(url, { type: 'replay' });
let awaiting = false;
for (let attempt = 0; attempt < 80; attempt++) {
  await new Promise(resolve => setTimeout(resolve, 250));
  awaiting = Boolean((await (await fetch(url)).json()).awaitingHumanConfirmation);
  if (awaiting) break;
}
assert.equal(awaiting, true);
assert.equal((await post(url, { type: 'confirm' })).status, 200);
assert.equal((await revised).status, 200);
state = await (await fetch(url)).json();
assert.equal(state.plans.length, 2);
assert.equal(state.plans[1].costPerPerson, 56);
assert.equal(state.phase, 'Agreed');
const maya = state.travelers.find(t => t.id === 'maya');
await post(url, { type: 'traveler', ...maya, availableDay: '2026-11-15' });
await post(url, { type: 'replay' });
state = await (await fetch(url)).json();
assert.equal(state.phase, 'Blocked');
assert.match(state.error, /different available days/);
await post(url, { type: 'reset' });
state = await (await fetch(url)).json();
assert.equal(state.events.length, 0);
assert.equal(state.plans.length, 0);
assert.equal(state.humanMessages.length, 1);
await post(url, { type: 'traveler', ...state.travelers.find(t => t.id === 'maya'), availableDay: '2026-11-14' });
state = await (await fetch(url)).json();
await post(url, { type: 'traveler', ...state.travelers.find(t => t.id === 'leo'), budget: 23 });
await post(url, { type: 'replay' });
state = await (await fetch(url)).json();
assert.equal(state.phase, 'Blocked');
assert.match(state.error, /Leo's \$23 budget.*\$24 per person/);
await post(url, { type: 'traveler', ...state.travelers.find(t => t.id === 'leo'), budget: 24 });
await post(url, { type: 'replay' });
state = await (await fetch(url)).json();
assert.equal(state.phase, 'Agreed');
assert.equal(state.plans[0].costPerPerson, 24);
console.log(JSON.stringify({ result: 'pass', create: true, reload: true, duplicateStart: true, firstCost: 128, revisedCost: 56, humanConfirmation: true, blockedConflicts: true, feasibleFloor: 24, resetScope: true }));
